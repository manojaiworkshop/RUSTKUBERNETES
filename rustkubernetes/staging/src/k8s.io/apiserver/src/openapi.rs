//! Minimal OpenAPI v3 publishing (`k8s.io/kube-openapi` handler3).
//!
//! `kubectl create/apply` ask `/openapi/v3` whether the server supports the
//! `fieldValidation` query parameter for a kind (by looking for a PATCH
//! operation tagged with `x-kubernetes-group-version-kind`). When it does,
//! kubectl relies on server-side validation instead of client-side schemas.
//!
//! Phase 1 publishes the paths and operations (no schemas yet).

use serde_json::{json, Map, Value};

use crate::registry::Registry;

fn gv_path(group: &str, version: &str) -> String {
    if group.is_empty() {
        format!("api/{version}")
    } else {
        format!("apis/{group}/{version}")
    }
}

/// `GET /openapi/v3`: index of group-version documents.
pub fn root(registry: &Registry, hash: &str) -> Value {
    let mut paths = Map::new();
    for (group, versions) in registry.groups() {
        for v in versions {
            let p = gv_path(&group, &v);
            paths.insert(p.clone(), json!({"serverRelativeURL": format!("/openapi/v3/{p}?hash={hash}")}));
        }
    }
    json!({"paths": paths})
}

/// Component name of `ObjectMeta`, referenced by published kinds.
pub const OBJECT_META: &str = "io.k8s.apimachinery.pkg.apis.meta.v1.ObjectMeta";

/// A short `ObjectMeta` schema (enough for `kubectl explain <kind>.metadata`).
fn object_meta_schema() -> Value {
    let s = |d: &str| json!({"type": "string", "description": d});
    json!({
        "description": "ObjectMeta is metadata that all persisted resources must have, which includes all objects users must create.",
        "type": "object",
        "properties": {
            "name": s("Name must be unique within a namespace. Is required when creating resources, although some resources may allow a client to request the generation of an appropriate name automatically. Name is primarily intended for creation idempotence and configuration definition. Cannot be updated. More info: https://kubernetes.io/docs/concepts/overview/working-with-objects/names#names"),
            "generateName": s("GenerateName is an optional prefix, used by the server, to generate a unique name ONLY IF the Name field has not been provided."),
            "namespace": s("Namespace defines the space within which each name must be unique. An empty namespace is equivalent to the \"default\" namespace, but \"default\" is the canonical representation. Not all objects are required to be scoped to a namespace - the value of this field for those objects will be empty."),
            "uid": s("UID is the unique in time and space value for this object. It is typically generated by the server on successful creation of a resource and is not allowed to change on PUT operations."),
            "resourceVersion": s("An opaque value that represents the internal version of this object that can be used by clients to determine when objects have changed."),
            "generation": {"type": "integer", "format": "int64", "description": "A sequence number representing a specific generation of the desired state. Populated by the system. Read-only."},
            "creationTimestamp": {"type": "string", "format": "date-time", "description": "CreationTimestamp is a timestamp representing the server time when this object was created."},
            "deletionTimestamp": {"type": "string", "format": "date-time", "description": "DeletionTimestamp is RFC 3339 date and time at which this resource will be deleted."},
            "labels": {"type": "object", "additionalProperties": {"type": "string"}, "description": "Map of string keys and values that can be used to organize and categorize (scope and select) objects. More info: https://kubernetes.io/docs/concepts/overview/working-with-objects/labels"},
            "annotations": {"type": "object", "additionalProperties": {"type": "string"}, "description": "Annotations is an unstructured key value map stored with a resource that may be set by external tools to store and retrieve arbitrary metadata. More info: https://kubernetes.io/docs/concepts/overview/working-with-objects/annotations"},
            "finalizers": {"type": "array", "items": {"type": "string"}, "description": "Must be empty before the object is deleted from the registry."},
        },
    })
}

fn param(name: &str, in_: &str) -> Value {
    json!({"name": name, "in": in_, "schema": {"type": "string", "uniqueItems": true}})
}

/// `GET /openapi/v3/api/v1`, `/openapi/v3/apis/<g>/<v>`.
pub fn group_version(registry: &Registry, path: &str, version_info: &str) -> Option<Value> {
    let parts: Vec<&str> = path.trim_matches('/').split('/').collect();
    let (group, version) = match parts.as_slice() {
        ["api", v] => ("", *v),
        ["apis", g, v] => (*g, *v),
        _ => return None,
    };
    let resources = registry.group_version(group, version);
    if resources.is_empty() {
        return None;
    }
    let base = format!("/{}", gv_path(group, version));
    let mut paths = Map::new();
    let mut schemas = Map::new();
    for r in &resources {
        if let Some((name, schema)) = r.strategy.openapi_schema() {
            schemas.insert(name, schema);
            schemas.entry(OBJECT_META.to_string()).or_insert_with(object_meta_schema);
        }
    }
    for r in resources {
        let gvk = json!({"group": r.group, "version": r.version, "kind": r.kind});
        let collection =
            if r.namespaced { format!("{base}/namespaces/{{namespace}}/{}", r.plural) } else { format!("{base}/{}", r.plural) };
        let item = format!("{collection}/{{name}}");
        let common = vec![param("dryRun", "query"), param("fieldManager", "query"), param("fieldValidation", "query")];
        let op = |id: &str, action: &str| {
            json!({
                "operationId": format!("{id}{}", r.kind),
                "x-kubernetes-action": action,
                "x-kubernetes-group-version-kind": gvk,
                "parameters": common,
                "responses": {"200": {"description": "OK"}},
            })
        };
        paths.insert(collection, json!({"post": op("create", "post"), "get": op("list", "list")}));
        paths.insert(
            item,
            json!({"get": op("read", "get"), "put": op("replace", "put"),
                   "patch": op("patch", "patch"), "delete": op("delete", "delete")}),
        );
    }
    Some(json!({
        "openapi": "3.0.0",
        "info": {"title": "Kubernetes", "version": version_info},
        "paths": paths,
        "components": {"schemas": schemas},
    }))
}
